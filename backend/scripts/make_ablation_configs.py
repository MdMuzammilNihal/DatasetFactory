"""Write leave-one-out ablation configs for a domain: copies of default.toml with one stage off.

    python scripts/make_ablation_configs.py medical   ->  config/ablations/medical-no-*.toml

Stages: global filter (all checks off), domain validator (all checks off), quality score
(threshold 0), learned classifier (enabled = false), deduplication (enabled = false);
plus DOMAIN-loose.toml (validator and score threshold both off).
Each edit must apply exactly once and every file must load, or the script fails.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from dataset_factory.config import GLOBAL_CHECKS, load_config  # noqa: E402
from dataset_factory.validators import build_validator  # noqa: E402


def _sub(text: str, pattern: str, repl: str) -> str:
    new, n = re.subn(pattern, repl, text, count=1, flags=re.M)
    if n != 1 or new == text:
        raise SystemExit(f"edit did not apply: {pattern!r}")
    return new


def main(domain: str) -> None:
    base = (ROOT / "config" / "default.toml").read_text(encoding="utf-8")
    checks = build_validator(domain).CHECKS
    q = lambda names: "[" + ", ".join(f'"{n}"' for n in names) + "]"  # noqa: E731
    edits = {
        "no-global": (r"^(\[global_filter\]\n(?:(?!^\[).*\n)*?)disabled_checks = \[\]",
                      r"\g<1>disabled_checks = " + q(GLOBAL_CHECKS)),
        "no-validator": (rf"^\[validators\.{domain}\]\n", f"[validators.{domain}]\ndisabled_checks = {q(checks)}\n"),
        "no-score": (rf"^(\[scoring\.{domain}\]\nthreshold = )[0-9.]+", r"\g<1>0.0"),
        "no-classifier": (r"^(\[classifier\]\nenabled = )true", r"\g<1>false"),
        "no-dedup": (r"^(\[dedup\]\nenabled = )true", r"\g<1>false"),
    }
    out = ROOT / "config" / "ablations"
    out.mkdir(parents=True, exist_ok=True)
    for name, (pat, repl) in edits.items():
        text = f"# Ablation: {domain} with stage '{name}' (generated by scripts/make_ablation_configs.py)\n" \
               + _sub(base, pat, repl)
        path = out / f"{domain}-{name}.toml"
        path.write_text(text, encoding="utf-8", newline="\n")
        load_config(path)
        print("wrote", path.relative_to(ROOT))
    # loose recipe: validator AND score threshold off (global, classifier, dedup, PII stay on)
    text = f"# Recipe: {domain} loose, validator and score threshold off (scripts/make_ablation_configs.py)\n" \
        + _sub(_sub(base, *edits["no-validator"]), *edits["no-score"])
    path = out / f"{domain}-loose.toml"
    path.write_text(text, encoding="utf-8", newline="\n")
    load_config(path)
    print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "medical")
